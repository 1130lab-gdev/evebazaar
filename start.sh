ensure_frontend() {
    if [ ! -d "$ROOT/evebazaar.com/node_modules" ]; then
        log start "evebazaar.com: node_modules missing, running npm install"
        if ! (cd "$ROOT/evebazaar.com" && npm install) >>"$LOG_DIR/evebazaar.com-install.log" 2>&1; then
            log fail "evebazaar.com: npm install failed -- see $LOG_DIR/evebazaar.com-install.log"
            return 1
        fi
    fi
    local state; state=$(service_state evebazaar.com "$FRONTEND_PORT")
    case "$state" in
        managed*)
            log skip "evebazaar.com already running (pid ${state#managed })"
            return 0
            ;;
        external)
            log skip "something is already listening on $FRONTEND_PORT (not started by this script) -- leaving it alone"
            return 0
            ;;
    esac
    log start "evebazaar.com (vite dev server)"
    start_bg evebazaar.com "$ROOT/evebazaar.com" npm run dev -- --port "$FRONTEND_PORT"
    if ! wait_for_tcp "$FRONTEND_PORT" 20; then
        log fail "evebazaar.com didn't open port $FRONTEND_PORT within 20s -- see $LOG_DIR/evebazaar.com.log"
        return 1
    fi
    log ok "evebazaar.com listening on $FRONTEND_PORT"
}

# ---------------------------------------------------------------------------
# Status / stop
# ---------------------------------------------------------------------------

print_status() {
    printf '\n%-18s %-10s %-8s %s\n' SERVICE STATE PID PORT
    local eve_state=down exch_state=down
    [ "$(docker_health "$EVE_DB_CONTAINER")" = "healthy" ] && eve_state=up
    [ "$(docker_health "$EXCHANGE_DB_CONTAINER")" = "healthy" ] && exch_state=up
    printf '%-18s %-10s %-8s %s\n' eve-db "$eve_state" - "$EVE_DB_PORT"
    printf '%-18s %-10s %-8s %s\n' exchange-db "$exch_state" - "$EXCHANGE_DB_PORT"

    local name port
    for name in database tgi ordermatcher risk exchange-webapi catalog-api map-api evebazaar.com; do
        case "$name" in
            ordermatcher) port=$ORDERMATCHER_PORT ;;
            risk) port=$RISK_PORT ;;
            exchange-webapi) port=$WEBAPI_PORT ;;
            catalog-api) port=$CATALOG_API_PORT ;;
            map-api) port=$MAP_API_PORT ;;
            evebazaar.com) port=$FRONTEND_PORT ;;
            *) port=- ;;
        esac
        if [ "$port" != - ]; then
            local state; state=$(service_state "$name" "$port")
            case "$state" in
                managed*) printf '%-18s %-10s %-8s %s\n' "$name" up "${state#managed }" "$port" ;;
                external) printf '%-18s %-10s %-8s %s\n' "$name" "up (external)" - "$port" ;;
                *) printf '%-18s %-10s %-8s %s\n' "$name" down - "$port" ;;
            esac
        elif pid_file_alive "$name"; then
            printf '%-18s %-10s %-8s %s\n' "$name" up "$(cat "$PID_DIR/$name.pid")" "$port"
        else
            printf '%-18s %-10s %-8s %s\n' "$name" down - "$port"
        fi
    done
    echo
    echo "logs: $LOG_DIR/<service>.log"
}

stop_all() {
    local name
    for name in evebazaar.com catalog-api map-api exchange-webapi risk ordermatcher tgi database; do
        stop_service "$name"
    done
    log note "eve-db/exchange-db (docker) left running -- 'docker compose -f <compose file> down' to stop them"
}

# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

ORDERMATCHER_JUST_STARTED=false

# Shared tail for every start_* profile below: print the final table, then
# fail the whole invocation (matching start_all's old behavior) if any
# ensure_* step in the profile failed.
finish_start() {
    local failed="$1"
    print_status
    if [ "$failed" -ne 0 ]; then
        log fail "one or more services failed to start -- see the [fail] lines and their logs above"
        exit 1
    fi
}

start_all() {
    local failed=0
    ensure_postgres eve-db "$EVE_DB_CONTAINER" "$EVE_DB_COMPOSE" "$EVE_DB_PORT" || failed=1
    ensure_postgres exchange-db "$EXCHANGE_DB_CONTAINER" "$EXCHANGE_DB_COMPOSE" "$EXCHANGE_DB_PORT" || failed=1
    ensure_database || failed=1
    ensure_catalog_api || failed=1
    ensure_map_api || failed=1
    ensure_tgi || failed=1
    ensure_ordermatcher || failed=1
    ensure_risk || failed=1
    ensure_webapi || failed=1
    ensure_frontend || failed=1
    finish_start "$failed"
}

# Haulers/runs/route-planner + login -- catalog-api's own auth reads
# exchange.users directly (see catalog-api/src/db/exchange_reads.rs), and
# account creation/login goes through exchange-webapi, so both of those
# are needed even though this profile never touches ordermatcher/risk.
start_hauling() {
    local failed=0
    ensure_postgres eve-db "$EVE_DB_CONTAINER" "$EVE_DB_COMPOSE" "$EVE_DB_PORT" || failed=1
    ensure_postgres exchange-db "$EXCHANGE_DB_CONTAINER" "$EXCHANGE_DB_COMPOSE" "$EXCHANGE_DB_PORT" || failed=1
    ensure_database || failed=1
    ensure_catalog_api || failed=1
    ensure_webapi || failed=1
    ensure_frontend || failed=1
    finish_start "$failed"
}

# The trading terminal, with real order matching (ordermatcher) and
# pre-trade margin checks (risk) -- both need eve-db/exchange-db, but
# neither needs the live mktdata sync loop (`database`) or catalog-api.
start_exchange() {
    local failed=0
    ensure_postgres eve-db "$EVE_DB_CONTAINER" "$EVE_DB_COMPOSE" "$EVE_DB_PORT" || failed=1
    ensure_postgres exchange-db "$EXCHANGE_DB_CONTAINER" "$EXCHANGE_DB_COMPOSE" "$EXCHANGE_DB_PORT" || failed=1
    ensure_ordermatcher || failed=1
    ensure_risk || failed=1
    ensure_webapi || failed=1
    ensure_frontend || failed=1
    finish_start "$failed"
}

case "${1:-start}" in
    start)
        case "${2:-all}" in
            all) start_all ;;
            hauling) start_hauling ;;
            exchange) start_exchange ;;
            *)
                echo "usage: $0 start [all|hauling|exchange]" >&2
                exit 2
                ;;
        esac
        ;;
    status) print_status ;;
    stop) stop_all ;;
    *)
        echo "usage: $0 [start [all|hauling|exchange]|status|stop]" >&2
        exit 2
        ;;
esac
