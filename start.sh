#!/usr/bin/env bash
# Brings up the whole evebazaar stack in dependency order:
#   eve-db, exchange-db (docker)
#     -> database (one-time full sync, then a --mode mktdata loop)
#     -> catalog-api, map-api (read-only against eve-db, no dependency on tgi/ordermatcher/risk/webapi)
#     -> tgi (--mode loop)
#     -> ordermatcher
#       -> risk
#       -> exchange-webapi
#         -> evebazaar.com (vite dev server)
#
# Safe to re-run: anything already up and healthy is left alone. The one
# exception is risk/exchange-webapi, which get restarted if ordermatcher
# had to be (re)started in *this* run -- see the note by
# ORDERMATCHER_JUST_STARTED below for why that's the only dependency worth
# forcing a restart over. Everything else (deadpool-backed Postgres access)
# reconnects lazily on its own; restarting it for a dependency coming back
# up would just be churn.
#
# `start` takes an optional profile so a focused test session doesn't have
# to pay for the whole stack:
#   ./start.sh start            everything (default)
#   ./start.sh start hauling    eve-db, exchange-db, database (mktdata),
#                                catalog-api, exchange-webapi, frontend --
#                                haulers/runs/route-planner plus login
#                                (auth reads exchange.users, so
#                                exchange-webapi/exchange-db are needed even
#                                though ordermatcher/risk aren't). Skips
#                                tgi/ordermatcher/risk/map-api.
#   ./start.sh start exchange   eve-db, exchange-db, ordermatcher, risk,
#                                exchange-webapi, frontend -- the trading
#                                terminal with real order matching and
#                                pre-trade risk checks. Skips
#                                tgi/database/catalog-api/map-api.
#
# `status` and `stop` are unaffected by profile -- they always show/stop
# whatever's actually running.
#
# Usage: ./start.sh [start [all|hauling|exchange]|status|stop]

set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RUN_DIR="$ROOT/.run"
PID_DIR="$RUN_DIR/pids"
LOG_DIR="$RUN_DIR/logs"
ENV_FILE="$ROOT/.env"
mkdir -p "$PID_DIR" "$LOG_DIR"

EVE_DB_CONTAINER=eve-database
EVE_DB_COMPOSE="$ROOT/database/database/docker-compose.yml"
EVE_DB_PORT=5532

EXCHANGE_DB_CONTAINER=eve-exchange-db
EXCHANGE_DB_COMPOSE="$ROOT/exchange-webapi/database/docker-compose.yml"
EXCHANGE_DB_PORT=5533

ORDERMATCHER_PORT=7301
RISK_PORT=8090
WEBAPI_PORT=8080
CATALOG_API_PORT=8091
MAP_API_PORT=8092
FRONTEND_PORT=5173

log() { printf '[%s] %s\n' "$1" "$2"; }

# Some machines (this one included) don't have the invoking user in the
# `docker` group, so plain `docker` gets a permission-denied on the socket
# and every docker call needs `sudo` in front of it. Detected lazily (only
# by the docker-touching functions below, not unconditionally at load time)
# so that e.g. stopping local processes doesn't print an irrelevant docker
# warning. A `sudo` fallback can still prompt for a password interactively,
# which is fine for a manually-run script but means this doesn't work
# unattended until the user is actually in the `docker` group.
DOCKER=()
detect_docker() {
    [ ${#DOCKER[@]} -gt 0 ] && return
    DOCKER=(docker)
    if ! docker info >/dev/null 2>&1; then
        DOCKER=(sudo docker)
        log note "docker isn't usable as $(whoami) without sudo -- falling back to 'sudo docker' (may prompt for your password). Run 'sudo usermod -aG docker $(whoami)' and re-login to fix this permanently."
    fi
}

# ---------------------------------------------------------------------------
# Secrets shared across processes. RISK_SHARED_SECRET must be identical in
# risk and exchange-webapi (webapi presents it to risk's /authorize), and
# risk's WEBAPI_ADMIN_API_KEY must equal exchange-webapi's ADMIN_API_KEY
# (risk uses it to call webapi's admin balance-adjust endpoint at EOD/sweep
# time). Neither mismatch fails loudly at boot, so generating both once and
# reusing them on every run is what keeps this actually automated instead
# of silently 401ing the first time interest accrual runs.
# ---------------------------------------------------------------------------
gen_secret() {
    if command -v openssl >/dev/null 2>&1; then
        openssl rand -hex 24
    else
        head -c 24 /dev/urandom | od -An -tx1 | tr -d ' \n'
    fi
}

if [ ! -f "$ENV_FILE" ]; then
    log new "generating $ENV_FILE with fresh shared secrets"
    {
        echo "# Auto-generated by start.sh on $(date -Is). Shared between risk and"
        echo "# exchange-webapi -- edit here, not in either service's own environment,"
        echo "# and re-run start.sh to pick up a change (existing processes won't"
        echo "# reload it on their own)."
        echo "ADMIN_API_KEY=$(gen_secret)"
        echo "RISK_SHARED_SECRET=$(gen_secret)"
    } >"$ENV_FILE"
fi
set -a
# shellcheck disable=SC1090
source "$ENV_FILE"
set +a
export WEBAPI_ADMIN_API_KEY="$ADMIN_API_KEY"
# exchange-webapi reads this to enable ordermatcher integration (see
# config.rs's matcher_addr) -- without it, orders persist but never reach
# the matching engine. Harmless to export even when ordermatcher isn't
# part of the profile being started: exchange-webapi just won't be able to
# connect, same as if this were unset.
export MATCHER_ADDR="127.0.0.1:$ORDERMATCHER_PORT"

# ---------------------------------------------------------------------------
# Generic process helpers
# ---------------------------------------------------------------------------

# Dev servers on this machine happily bind IPv6-loopback only (vite's
# default "localhost" bind resolves to ::1 here, not 127.0.0.1) -- checking
# only one family silently misses those, so both are tried.
is_tcp_open() {
    local port="$1"
    (exec 3<>"/dev/tcp/127.0.0.1/$port") 2>/dev/null && { exec 3>&- 2>/dev/null; return 0; }
    (exec 3<>"/dev/tcp/::1/$port") 2>/dev/null && { exec 3>&- 2>/dev/null; return 0; }
    return 1
}

wait_for_tcp() {
    local port="$1" timeout="${2:-30}"
    local waited=0
    while ! is_tcp_open "$port"; do
        sleep 1
        waited=$((waited + 1))
        [ "$waited" -ge "$timeout" ] && return 1
    done
    return 0
}

pid_file_alive() {
    local name="$1"
    local pid_file="$PID_DIR/$name.pid"
    [ -f "$pid_file" ] || return 1
    local pid
    pid=$(cat "$pid_file")
    [ -n "$pid" ] && kill -0 "$pid" 2>/dev/null
}

# Echoes "managed <pid>" | "external" | "down" for a port-bound service.
# "external" matters in practice: something can already be listening on a
# service's port without this script having started it (a manually-run
# `cargo run`, a leftover process from before this script existed, etc).
# Port liveness is treated as authoritative over our own pid file, so we
# never try to double-bind a port a pid-file check alone would have missed.
service_state() {
    local name="$1" port="$2"
    if is_tcp_open "$port"; then
        if pid_file_alive "$name"; then
            echo "managed $(cat "$PID_DIR/$name.pid")"
        else
            echo "external"
        fi
    else
        echo "down"
    fi
}

# Backgrounds "$@" with cwd "$workdir", capturing the *actual* binary's PID
# (not a `cargo run`/`npm` wrapper's) by exec-ing inside the backgrounded
# subshell -- exec replaces the subshell's process image instead of forking
# a child, so `$!` is already the real process and `kill` on it works
# directly with no orphaned wrapper left behind.
start_bg() {
    local name="$1" workdir="$2"; shift 2
    {
        echo "===== $(date -Is) starting $name ====="
    } >>"$LOG_DIR/$name.log"
    (cd "$workdir" && exec "$@") >>"$LOG_DIR/$name.log" 2>&1 &
    local pid=$!
    disown "$pid" 2>/dev/null || true
    echo "$pid" >"$PID_DIR/$name.pid"
}

stop_service() {
    local name="$1"
    pid_file_alive "$name" || { rm -f "$PID_DIR/$name.pid"; return 0; }
    local pid
    pid=$(cat "$PID_DIR/$name.pid")
    log stop "$name (pid $pid)"
    kill "$pid" 2>/dev/null
    for _ in $(seq 1 10); do
        kill -0 "$pid" 2>/dev/null || break
        sleep 0.5
    done
    kill -0 "$pid" 2>/dev/null && kill -9 "$pid" 2>/dev/null
    rm -f "$PID_DIR/$name.pid"
}

build_rust() {
    local project="$1"
    log build "$project"
    if ! (cd "$ROOT/$project" && cargo build --quiet) >>"$LOG_DIR/$project-build.log" 2>&1; then
        log fail "$project failed to build -- see $LOG_DIR/$project-build.log"
        return 1
    fi
}

# ---------------------------------------------------------------------------
# Docker-backed Postgres instances
# ---------------------------------------------------------------------------

docker_health() {
    detect_docker
    "${DOCKER[@]}" inspect -f '{{.State.Health.Status}}' "$1" 2>/dev/null
}

ensure_postgres() {
    local label="$1" container="$2" compose_file="$3" port="$4"
    if [ "$(docker_health "$container")" = "healthy" ]; then
        log skip "$label already up and healthy (container $container, port $port)"
        return 0
    fi
    log start "$label (docker compose, container $container)"
    if ! "${DOCKER[@]}" compose -f "$compose_file" up -d >>"$LOG_DIR/$label.log" 2>&1; then
        log fail "$label failed to start -- see $LOG_DIR/$label.log (if it mentions the docker socket, this is the sudo/docker-group issue noted above)"
        return 1
    fi
    local waited=0
    while [ "$(docker_health "$container")" != "healthy" ]; do
        sleep 1
        waited=$((waited + 1))
        if [ "$waited" -ge 30 ]; then
            log fail "$label never became healthy within 30s"
            return 1
        fi
    done
    log ok "$label healthy"
}

# ---------------------------------------------------------------------------
# database: needs at least one full sync (taxonomy+universe+market) before
# a --mode mktdata loop is useful -- mktdata only syncs orders for regions
# that already exist, so on a genuinely empty eve DB it would loop forever
# doing nothing. Detected via the `regions` table (always present, created
# by the DB's own init SQL on first container boot regardless of whether
# database has ever run).
# ---------------------------------------------------------------------------

ensure_database() {
    build_rust database || return 1
    detect_docker

    local region_count
    region_count=$("${DOCKER[@]}" exec "$EVE_DB_CONTAINER" psql -U eve -d eve -tAc "SELECT COUNT(*) FROM regions" 2>/dev/null || echo "")
    if [ -z "$region_count" ] || [ "$region_count" -eq 0 ]; then
        log start "database: eve DB is empty, running one-time full sync (talks to live ESI, can take a while)"
        if ! (cd "$ROOT/database" && ./target/debug/database --mode sync) 2>&1 | tee "$LOG_DIR/database-initial-sync.log"; then
            log fail "database: initial full sync failed -- see $LOG_DIR/database-initial-sync.log"
            return 1
        fi
        log ok "database: initial full sync complete"
    fi

    if pid_file_alive database; then
        log skip "database mktdata loop already running (pid $(cat "$PID_DIR/database.pid"))"
        return 0
    fi
    log start "database (--mode mktdata loop)"
    start_bg database "$ROOT/database" ./target/debug/database --mode mktdata
}

ensure_tgi() {
    build_rust tgi || return 1
    if pid_file_alive tgi; then
        log skip "tgi already running (pid $(cat "$PID_DIR/tgi.pid"))"
        return 0
    fi
    log start "tgi (--mode loop)"
    start_bg tgi "$ROOT/tgi" ./target/debug/tgi --mode loop
}

ensure_ordermatcher() {
    build_rust ordermatcher || return 1
    ORDERMATCHER_JUST_STARTED=false
    local state; state=$(service_state ordermatcher "$ORDERMATCHER_PORT")
    case "$state" in
        managed*)
            log skip "ordermatcher already running (pid ${state#managed })"
            return 0
            ;;
        external)
            log skip "something is already listening on $ORDERMATCHER_PORT (not started by this script) -- leaving it alone"
            return 0
            ;;
    esac
    log start "ordermatcher"
    start_bg ordermatcher "$ROOT/ordermatcher" ./target/debug/ordermatcher
    if ! wait_for_tcp "$ORDERMATCHER_PORT" 20; then
        log fail "ordermatcher didn't open port $ORDERMATCHER_PORT within 20s -- see $LOG_DIR/ordermatcher.log"
        return 1
    fi
    log ok "ordermatcher listening on $ORDERMATCHER_PORT"
    ORDERMATCHER_JUST_STARTED=true
}

ensure_risk() {
    build_rust risk || return 1
    local state; state=$(service_state risk "$RISK_PORT")

    if [[ "$state" == managed* ]] && [ "$ORDERMATCHER_JUST_STARTED" = true ]; then
        log restart "risk was running before ordermatcher came up -- restarting for a clean reconnect"
        stop_service risk
        state=down
    fi

    case "$state" in
        managed*)
            log skip "risk already running (pid ${state#managed })"
            return 0
            ;;
        external)
            log skip "something is already listening on $RISK_PORT (not started by this script) -- leaving it alone"
            return 0
            ;;
    esac
    log start "risk"
    start_bg risk "$ROOT/risk" ./target/debug/risk
    if ! wait_for_tcp "$RISK_PORT" 20; then
        log fail "risk didn't open port $RISK_PORT within 20s -- see $LOG_DIR/risk.log"
        return 1
    fi
    log ok "risk listening on $RISK_PORT"
}

